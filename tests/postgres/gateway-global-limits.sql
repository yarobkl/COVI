-- COVI SQL draft security regression: globally shared per-installation quotas.
-- Disposable covi_ci only; never run in production.
-- A malicious caller must not gain unlimited quota by changing untrusted IP headers
-- or repeatedly guessing new public token UUIDs.
begin;
set local role service_role;
do $global_limits$
declare
  v_kind text;
  v_limit integer;
  v_digest text;
  v_ok boolean;
begin
  for v_kind, v_limit in
    select * from (values
      ('catalog_global_minute'::text,1200),
      ('status_global_minute'::text,1200),
      ('order_global_minute'::text,300)
    ) as quotas(kind, cap)
  loop
    -- Pre-fill a unique bucket to its threshold without 1200 network calls.
    v_digest := repeat(case v_kind
      when 'catalog_global_minute' then 'c'
      when 'status_global_minute' then 'd'
      else 'e' end,64);
    insert into public.checkout_gateway_rate_windows
      (digest,bucket_kind,bucket_start,hits)
    values (v_digest,v_kind,date_trunc('minute',clock_timestamp()),v_limit)
    on conflict (digest,bucket_kind,bucket_start)
    do update set hits=excluded.hits;
    v_ok := public.consume_checkout_gateway_quota(v_digest,v_kind);
    if v_ok is distinct from false then
      raise exception 'Global quota bypass for % at limit %',v_kind,v_limit;
    end if;
    -- Another installation-wide digest remains independent; the same digest
    -- must be shared for ALL tokens when generated by the gateway.
    v_ok := public.consume_checkout_gateway_quota(repeat('f',64),v_kind);
    if v_ok is distinct from true then
      raise exception 'Fresh global quota unexpectedly blocked for %',v_kind;
    end if;
  end loop;
end;
$global_limits$;
commit;
select 'PASS: Shared gateway ceilings cannot be exceeded by new token/source keys' as result;
